import { readFile, writeFile } from 'node:fs/promises'
import { createEchoTheme } from 'echo-ui-core/theme'

const config = JSON.parse(await readFile(new URL('../echo.json', import.meta.url), 'utf8'))
const { css } = createEchoTheme(
    { ...config.seed, chassis: '#ffffff', paper: '#211f2b' },
    { selector: ':root:not([data-theme="dark"])' },
)
// Store previews and marketing device screens render their own dark brand palette.
const embedded = createEchoTheme(config.seed, {
    selector: '.oliva-screen, .iphone-screen, .store-preview',
}).css
await writeFile(
    new URL('../src/components/echo/echo-theme-light.css', import.meta.url),
    '/* Generated by scripts/generate-appearance-theme.mjs with echo-ui-core. Do not edit roles by hand. */\n' +
        css +
        '\n' +
        embedded +
        '\n',
)
